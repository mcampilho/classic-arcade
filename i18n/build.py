#!/usr/bin/env python3
"""Generates i18n/strings.gd from i18n/strings.json ({"English text": ["português", "español"]}).

Keys and translations are written exactly as in the GDScript source (with \\n, \\" ...).
Fails (exit code 1) if an entry does not have exactly one non-empty text per language.
Usage: python3 i18n/build.py
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
LANGS = ["pt", "es"]          # the languages after English, in the order of I18n.LANGS


def lit(s: str) -> str:
    """GDScript string literal: escapes are already in the text; only bare quotes need one."""
    out, i = "", 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            out += s[i:i + 2]
            i += 2
            continue
        out += '\\"' if c == '"' else ("\\n" if c == "\n" else c)
        i += 1
    return '"' + out + '"'


def main() -> int:
    table = json.loads((HERE / "strings.json").read_text(encoding="utf-8"))
    bad = [k for k, v in table.items()
           if not isinstance(v, list) or len(v) != len(LANGS) or not all(isinstance(s, str) and s for s in v)]
    for k in bad:
        print(f"bad entry: {k!r} -> {table[k]!r}", file=sys.stderr)
    if bad:
        return 1
    lines = ["extends RefCounted",
             "## Generated by i18n/build.py from i18n/strings.json — do not edit by hand.",
             "## Key: original English text; value: [" + ", ".join(LANGS) + "].", "", "const T := {"]
    for k in sorted(table):
        lines.append("\t%s: [%s]," % (lit(k), ", ".join(lit(s) for s in table[k])))
    lines.append("}")
    (HERE / "strings.gd").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(len(table), "texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
